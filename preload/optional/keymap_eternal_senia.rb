# 00_keymap.rb (이터널 세니아용)
# 이 파일은 01_win32_wrap_pad.rb 보다 먼저 로드되어야 함
#
# 이터널 세니아가 Kboard로 감지하는 키:
#   C키 → 레시피 조합
#   E키 → E 스킬 (R1 버튼)
#   R키 → R 스킬 (R2 버튼)

$KEYMAP_PAD = {
  :C => :X,    # 키보드 C → Pad X (레시피 조합)
  :E => :A,    # 키보드 E → R1 (:A 심볼이 실제로 R1에 바인딩됨)
  :R => :Z,    # 키보드 R → R2 (:Z 심볼이 실제로 R2에 바인딩됨)
}